function makeStep(
  partial: Omit<MealStep, 'status' | 'remainingSec' | 'addedMin' | 'readyBeforeIds' | 'mustFinishByDinner'> & {
    readyBeforeIds?: string[];
    mustFinishByDinner?: boolean;
  }
): MealStep {
  return {
    ...partial,
    readyBeforeIds: partial.readyBeforeIds ?? [],
    mustFinishByDinner: partial.mustFinishByDinner ?? true,
    status: 'pending',
    remainingSec: partial.durationMin * 60,
    addedMin: 0,
  };
}

